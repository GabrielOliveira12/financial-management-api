CREATE TABLE tb_transaction
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT         NOT NULL,
    destination_user_id BIGINT,
    type                VARCHAR(20)    NOT NULL,
    amount              NUMERIC(19, 2) NOT NULL,
    occurred_at         TIMESTAMP      NOT NULL,
    description         VARCHAR(255),
    category            VARCHAR(30),
    status              VARCHAR(20)    NOT NULL,
    rejection_reason    VARCHAR(40),
    created_at          TIMESTAMP      NOT NULL,

    CONSTRAINT chk_tb_transaction_amount
        CHECK (amount > 0),

    CONSTRAINT chk_tb_transaction_category
        CHECK (
            (type = 'PURCHASE' AND category IS NOT NULL)
                OR
            (type <> 'PURCHASE' AND category IS NULL)
            ),

    CONSTRAINT chk_tb_transaction_destination_user
        CHECK (
            (type = 'TRANSFER'
                AND destination_user_id IS NOT NULL
                AND destination_user_id <> user_id)
                OR
            (type <> 'TRANSFER' AND destination_user_id IS NULL)
            ),

    CONSTRAINT chk_tb_transaction_rejection_reason
        CHECK (
            (status = 'APPROVED' AND rejection_reason IS NULL)
                OR
            (status = 'REJECTED' AND rejection_reason IS NOT NULL)
            )
);

CREATE INDEX idx_tb_transaction_user_id
    ON tb_transaction (user_id);

CREATE INDEX idx_tb_transaction_user_id_occurred_at
    ON tb_transaction (user_id, occurred_at DESC);
